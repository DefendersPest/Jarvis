"""Render the CEO report as Markdown (archive / preview) and as a Teams Adaptive Card."""

from __future__ import annotations

import html

from jarvis.delivery.fmt import metric_value, num, pct, usd

KPI_ROWS = [
    ("Billed revenue", "revenue_billed_day", "revenue_billed_mtd"),
    ("Collections", "revenue_collected_day", "revenue_collected_mtd"),
    ("New customers", "new_customers_day", "new_customers_mtd"),
    ("Subscriptions sold", "new_subscriptions_day", "new_subscriptions_mtd"),
    ("Annual value sold", "sold_annual_value_day", "sold_annual_value_mtd"),
    ("Cancellations", "cancellations_day", "cancellations_mtd"),
    ("Annual value cancelled", "cancelled_annual_value_day", "cancelled_annual_value_mtd"),
]
OPS_ROWS = [
    "appointments_scheduled_day", "appointments_completed_day", "completion_rate_day",
    "appointments_missed_day", "appointments_no_show_day", "appointments_rescheduled_day",
    "appointments_cancelled_day", "completed_without_invoice_day", "avg_ticket_day",
]
STATUS_ICON = {"on_track": "On track", "at_risk": "At risk", "behind": "Behind"}


def _goal_text(m: dict) -> str:
    g = m.get("goal")
    if not g:
        return "no goal set" if m["status"] == "available" else ""
    if g["period"] == "monthly":
        return f"{STATUS_ICON[g['status']]} - {pct(g['attainment_pct'])} of pace (goal {_fmt(g['target'], m['unit'])}/mo)"
    return f"{STATUS_ICON[g['status']]} - {pct(g['attainment_pct'])} of goal ({_fmt(g['expected_to_date'], m['unit'])})"


def _fmt(v, unit):
    return usd(v) if unit == "usd" else pct(v) if unit == "pct" else num(v)


def unavailable_list(facts: dict) -> list[str]:
    out = []
    for c in facts["companies"]:
        for m in c["metrics"].values():
            if m["status"] == "unavailable":
                out.append(f"{c['company_name']} - {m['label']}: {m['reason']}")
    return out


# --------------------------------------------------------------------------- markdown
def to_markdown(facts: dict, narrative: dict, meta: dict) -> str:
    L: list[str] = []
    if facts.get("sample_data"):
        L += ["> **SAMPLE DATA - NOT REAL.** Generated by the offline prototype; no FieldRoutes data was used.", ""]
    L += [f"# JARVIS Daily CEO Intelligence Report", f"**Period:** {facts['period']['label']}  ",
          f"**Month-to-date:** {facts['period']['mtd_start']} to {facts['period']['mtd_end']}  ",
          f"**Generated:** {meta['generated_at']}", ""]
    L += [f"## {narrative['headline']}", "", narrative["executive_summary"], ""]
    L += ["## Top 3 actions", ""]
    for i, a in enumerate(narrative["top_actions"], 1):
        L += [f"{i}. **{a['title']}** ({a['owner']})  ", f"   {a['why']}"]
    L.append("")
    if narrative.get("watch_items"):
        L += ["## Watch list", ""] + [f"- {w}" for w in narrative["watch_items"]] + [""]

    port = facts["portfolio"]["metrics"]
    if len(facts["companies"]) > 1:
        L += ["## Portfolio", "", "| Metric | Period | MTD |", "|---|---:|---:|"]
        for label, dk, mk in KPI_ROWS:
            L.append(f"| {label} | {metric_value(port[dk])} | {metric_value(port[mk])} |")
        L.append("")

    for c in facts["companies"]:
        m = c["metrics"]
        L += [f"## {c['company_name']}", "", "| Metric | Period | MTD | vs goal (MTD) |", "|---|---:|---:|---|"]
        for label, dk, mk in KPI_ROWS:
            L.append(f"| {label} | {metric_value(m[dk])} | {metric_value(m[mk])} | {_goal_text(m[mk])} |")
        L += ["", "**Operations**", "", "| Metric | Value | vs goal |", "|---|---:|---|"]
        for k in OPS_ROWS:
            L.append(f"| {m[k]['label']} | {metric_value(m[k])} | {_goal_text(m[k]) if m[k].get('goal') else ''} |")
        L.append("")

        t = c["technicians"]
        L += ["**Technician production**", ""]
        if t["status"] == "unavailable":
            L += [f"_Unavailable: {t['reason']}_", ""]
        else:
            if t["reason"]:
                L += [f"_{t['reason']}_", ""]
            L += ["| Technician | Scheduled | Completed | Missed | Completion | Production | Avg/stop |",
                  "|---|---:|---:|---:|---:|---:|---:|"]
            for r in t["rows"]:
                L.append(f"| {r['technician']} | {r['scheduled']} | {r['completed']} | {r['missed']} | "
                         f"{pct(r['completion_rate'])} | {usd(r['production'])} | {usd(r['avg_per_stop'], True)} |")
            L.append("")

        s = c["sales_reps"]
        L += ["**Sales performance**", ""]
        if s["status"] == "unavailable":
            L += [f"_Unavailable: {s['reason']}_", ""]
        else:
            L += ["| Rep | Sold (period) | Sold MTD | Annual value (period) | Annual value MTD |", "|---|---:|---:|---:|---:|"]
            for r in s["rows"]:
                L.append(f"| {r['rep']} | {r['sold_day']} | {r['sold_mtd']} | {usd(r['annual_value_day'])} | {usd(r['annual_value_mtd'])} |")
            L.append("")

        if len(c["branches"]) > 1:
            L += ["**By branch**", "", "| Branch | Billed | Billed MTD | Completed | Missed | Sold MTD | Cancelled MTD |",
                  "|---|---:|---:|---:|---:|---:|---:|"]
            for b in c["branches"]:
                L.append(f"| {b['branch']} | {usd(b.get('revenue_billed_day'))} | {usd(b.get('revenue_billed_mtd'))} | "
                         f"{num(b.get('completed_day'))} | {num(b.get('missed_day'))} | {num(b.get('sold_mtd'))} | {num(b.get('cancelled_mtd'))} |")
            L.append("")

        issues = [f for f in c["findings"] if f["severity"] != "info"]
        if issues:
            L += ["**Issues detected**", ""] + [f"- [{f['severity'].upper()}] {f['title']}" for f in issues] + [""]

    un = unavailable_list(facts)
    L += ["## Data availability", ""]
    L += ([f"- {u}" for u in un] if un else ["All metrics were available from source data."]) + [""]
    L += ["---", f"_Narrative: {meta['narrative_source']}. All figures are computed from source records; "
          "metrics without source data are shown as UNAVAILABLE, never estimated._"]
    return "\n".join(L)


# --------------------------------------------------------------------------- adaptive card
def _text(t, **kw):
    return {"type": "TextBlock", "text": t, "wrap": True, **kw}


def to_adaptive_card(facts: dict, narrative: dict, meta: dict) -> dict:
    body: list[dict] = []
    if facts.get("sample_data"):
        body.append({"type": "Container", "style": "attention", "items": [
            _text("SAMPLE DATA - NOT REAL. Prototype output; no FieldRoutes data was used.", weight="Bolder")]})
    body += [
        _text("JARVIS Daily CEO Report", size="Large", weight="Bolder"),
        _text(f"{facts['period']['label']} | MTD through {facts['period']['mtd_end']}", isSubtle=True, spacing="None"),
        _text(narrative["headline"], weight="Bolder", size="Medium"),
        _text(narrative["executive_summary"]),
        _text("Top 3 actions", weight="Bolder", spacing="Medium"),
    ]
    for i, a in enumerate(narrative["top_actions"], 1):
        body.append(_text(f"**{i}. {a['title']}** - {a['owner']}\n\n{a['why']}"))

    port = facts["portfolio"]["metrics"]
    facts_rows = [{"title": label, "value": f"{metric_value(port[dk])} | MTD {metric_value(port[mk])}"}
                  for label, dk, mk in KPI_ROWS[:6]]
    facts_rows.append({"title": "Completed / missed",
                       "value": f"{metric_value(port['appointments_completed_day'])} / {metric_value(port['appointments_missed_day'])}"})
    body += [_text("Portfolio" if len(facts["companies"]) > 1 else "Key numbers", weight="Bolder", spacing="Medium"),
             {"type": "FactSet", "facts": facts_rows}]

    for c in facts["companies"]:
        m = c["metrics"]
        rows = []
        for k in ("revenue_billed_mtd", "revenue_collected_mtd", "new_subscriptions_mtd", "completion_rate_day"):
            g = _goal_text(m[k]) if m[k].get("goal") else ""
            rows.append({"title": m[k]["label"], "value": metric_value(m[k]) + (f" ({g})" if g else "")})
        tops = [r for r in c["technicians"]["rows"] if r["technician"] != "Unassigned"][:3]
        if tops:
            rows.append({"title": "Top technicians",
                         "value": ", ".join(f"{r['technician']} {usd(r['production'])}" if r["production"] is not None
                                            else f"{r['technician']} {r['completed']} stops" for r in tops)})
        body += [_text(c["company_name"], weight="Bolder", spacing="Medium"), {"type": "FactSet", "facts": rows}]
        issues = [f["title"] for f in c["findings"] if f["severity"] in ("high", "medium")][:4]
        if issues:
            body.append(_text("\n".join(f"- {t}" for t in issues), size="Small"))

    un = unavailable_list(facts)
    if un:
        body += [_text("Unavailable metrics", weight="Bolder", spacing="Medium", color="Warning"),
                 _text("\n".join(f"- {u}" for u in un[:8]) + (f"\n- ...and {len(un) - 8} more" if len(un) > 8 else ""),
                       size="Small")]
    body.append(_text(f"Narrative: {meta['narrative_source']} | Run {meta['run_id']}", size="Small", isSubtle=True))
    return {"type": "AdaptiveCard", "$schema": "http://adaptivecards.io/schemas/adaptive-card.json",
            "version": "1.4", "msteams": {"width": "Full"}, "body": body}


def to_html(markdown_text: str) -> str:
    """Minimal standalone HTML preview of the Markdown report (no external deps)."""
    out, in_table, in_list = [], False, False
    for line in markdown_text.splitlines():
        esc = html.escape(line)
        esc = _inline(esc)
        if line.startswith("|"):
            cells = [c.strip() for c in line.strip("|").split("|")]
            if set("".join(cells)) <= set("-: "):
                continue
            if not in_table:
                out.append("<table>")
                in_table = True
                out.append("<tr>" + "".join(f"<th>{_inline(html.escape(c))}</th>" for c in cells) + "</tr>")
            else:
                out.append("<tr>" + "".join(f"<td>{_inline(html.escape(c))}</td>" for c in cells) + "</tr>")
            continue
        if in_table:
            out.append("</table>")
            in_table = False
        if line.startswith("- "):
            if not in_list:
                out.append("<ul>")
                in_list = True
            out.append(f"<li>{_inline(html.escape(line[2:]))}</li>")
            continue
        if in_list:
            out.append("</ul>")
            in_list = False
        if line.startswith("# "):
            out.append(f"<h1>{_inline(html.escape(line[2:]))}</h1>")
        elif line.startswith("## "):
            out.append(f"<h2>{_inline(html.escape(line[3:]))}</h2>")
        elif line.startswith("> "):
            out.append(f"<div class='banner'>{_inline(html.escape(line[2:]))}</div>")
        elif line.strip() == "---":
            out.append("<hr>")
        elif line.strip():
            out.append(f"<p>{esc}</p>")
    if in_table:
        out.append("</table>")
    if in_list:
        out.append("</ul>")
    css = ("body{font-family:Segoe UI,system-ui,sans-serif;max-width:980px;margin:24px auto;padding:0 16px;color:#1b1b1b}"
           "table{border-collapse:collapse;margin:8px 0 16px;font-size:14px;width:100%}"
           "th,td{border:1px solid #ddd;padding:4px 8px;text-align:right}th:first-child,td:first-child{text-align:left}"
           "th{background:#f3f4f6}.banner{background:#fde68a;padding:8px 12px;border-radius:6px;font-weight:600}"
           "h2{margin-top:28px;border-bottom:2px solid #0f5132;padding-bottom:4px}")
    return f"<!doctype html><html><head><meta charset='utf-8'><title>JARVIS CEO Report</title><style>{css}</style></head><body>{''.join(out)}</body></html>"


def _inline(s: str) -> str:
    import re
    s = re.sub(r"\*\*(.+?)\*\*", r"<strong>\1</strong>", s)
    s = re.sub(r"(?<!\w)_(.+?)_(?!\w)", r"<em>\1</em>", s)
    return s
